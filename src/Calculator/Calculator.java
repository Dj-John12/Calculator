      private void showLoanDialog() {
         javax.swing.JTextField tfPrincipal = new javax.swing.JTextField(jtxtResult.getText(), 10);
        javax.swing.JTextField tfRate = new javax.swing.JTextField(10);
        javax.swing.JTextField tfMonths = new javax.swing.JTextField(10);

        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 2, 8, 8));
        panel.add(new javax.swing.JLabel("Amount of loan (₱):"));
        panel.add(tfPrincipal);
        panel.add(new javax.swing.JLabel("Interest per year (%):"));
        panel.add(tfRate);
        panel.add(new javax.swing.JLabel("Number of months:"));
        panel.add(tfMonths);

        int choice = javax.swing.JOptionPane.showConfirmDialog(this, panel,
                "Loan Calculator",
                javax.swing.JOptionPane.OK_CANCEL_OPTION,
                javax.swing.JOptionPane.PLAIN_MESSAGE);
        if (choice != javax.swing.JOptionPane.OK_OPTION) {
            return;
        }

        try {
            double p = Double.parseDouble(tfPrincipal.getText().trim().replace(",", ""));
            double rate = Double.parseDouble(tfRate.getText().trim());
            int n = Integer.parseInt(tfMonths.getText().trim());

            if (p <= 0 || rate < 0 || n <= 0) {
                throw new NumberFormatException();
            }

            double r = rate / 100 / 12;
            double monthly = (r == 0) ? p / n : p * r / (1 - Math.pow(1 + r, -n));
            double total = monthly * n;

            javax.swing.JOptionPane.showMessageDialog(this,
                    String.format("Monthly payment:  ₱%,.2f%n"
                            + "Total payment:  ₱%,.2f%n"
                            + "Total interest:  ₱%,.2f", monthly, total, total - p),
                    "Result", javax.swing.JOptionPane.INFORMATION_MESSAGE);

            jtxtResult.setText(String.format("%.2f", monthly));
            addHistory(String.format("Loan %.0f @%.2f%% x%dmo = %.2f", p, rate, n, monthly));

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please enter valid numbers (greater than 0).",
                    "Invalid input", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    
    }
   
