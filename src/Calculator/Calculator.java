    private void jbtnPointActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnPointActionPerformed
          
            prepareInput();
        String t = jtxtResult.getText();
        int i = t.length();
        while (i > 0 && (Character.isDigit(t.charAt(i - 1)) || t.charAt(i - 1) == '.')) {
            i--;
        }
        String lastNum = t.substring(i);
        if (lastNum.contains(".")) {
            return;
        }
        if (t.endsWith(")")) {
            t += " * ";
        }
        jtxtResult.setText(t + (lastNum.isEmpty() ? "0." : "."));
    }//GEN-LAST:event_jbtnPointActionPerformed

