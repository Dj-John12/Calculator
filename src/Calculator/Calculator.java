    private String removeLastOperator(String t) {
        t = t.substring(0, t.length() - 1);
        t = t.endsWith("mod") ? t.substring(0, t.length() - 3) : t.substring(0, t.length() - 1);
        return t.endsWith(" ") ? t.substring(0, t.length() - 1) : t;
    }

    private void openParen() {
        prepareInput();
        String t = jtxtResult.getText();
        if (!t.isEmpty() && (Character.isDigit(t.charAt(t.length() - 1)) || t.endsWith(")"))) {
            t += " * ";                             // 2( ) = 2 * ( )
        }
        jtxtResult.setText(t + "(");
    }
    
